"""
discover.py — Lead discovery engine.

Runs the search queries generated by query_gen.py through DuckDuckGo (ddgs),
parses the results into structured lead records (company, domain, website,
source), deduplicates by domain, respects the suppression list, and inserts
new leads into the database with status='new'.

Key design choices:
- All network calls use retry with exponential backoff + jitter.
- Suppressed domains/emails are skipped silently.
- Caps the number of actioned leads at MAX_ACTIONS_PER_RUN to avoid
  runaway API usage.
- Never fabricates data: only company and website derived from search
  results are stored. No revenue, employee counts, or invented facts.
"""

import logging
import os
import random
import re
import time
from urllib.parse import urlparse

from config import MAX_ACTIONS_PER_RUN
from db import upsert_lead, is_suppressed, get_lead_by_domain
from query_gen import generate_queries

logger = logging.getLogger("gtm.discover")


# ---------------------------------------------------------------------------
# Retry helper
# ---------------------------------------------------------------------------

def _retry_with_backoff(func, max_retries=3, base_delay=1.0, *args, **kwargs):
    """
    Call func with exponential backoff + jitter.

    On each failure, waits base_delay * (2 ** attempt) + random jitter
    before retrying. Raises the last exception after max_retries.
    """
    last_exc = None
    for attempt in range(max_retries):
        try:
            return func(*args, **kwargs)
        except Exception as exc:
            last_exc = exc
            if attempt < max_retries - 1:
                delay = base_delay * (2 ** attempt) + random.uniform(0, 1)
                logger.warning(
                    "Attempt %d failed (%s), retrying in %.1fs",
                    attempt + 1, type(exc).__name__, delay,
                )
                time.sleep(delay)
    raise last_exc


# ---------------------------------------------------------------------------
# Domain / company parsing
# ---------------------------------------------------------------------------

def _extract_domain(url):
    """Extract the root domain from a URL."""
    if not url:
        return ""
    if not url.startswith(("http://", "https://")):
        url = "https://" + url
    parsed = urlparse(url)
    host = parsed.netloc
    # Strip leading "www."
    if host.startswith("www."):
        host = host[4:]
    return host


def _derive_company_name(url, title=None):
    """
    Derive a company name from a URL and optional page title.

    Falls back to the domain (stripped of TLD) if no title is available.
    """
    domain = _extract_domain(url)
    if title:
        # Use the title if it looks like a company name (short, no " - " split).
        title = title.strip().split(" - ")[0].split(" | ")[0]
        if len(title) <= 60:
            return title
    # Fallback: use the domain name.
    name = domain.split(".")[0] if "." in domain else domain
    return name.replace("-", " ").replace("_", " ").title()


def _parse_search_result(result, source):
    """
    Convert a single DuckDuckGo result dict into a lead dict.

    DuckDuckGo results from ddgs have keys: title, href, body.
    """
    url = result.get("href", "")
    if not url:
        return None

    domain = _extract_domain(url)
    if not domain:
        return None

    company = _derive_company_name(url, result.get("title"))
    return {
        "company": company,
        "domain": domain,
        "website": url,
        "source": source,
    }


# ---------------------------------------------------------------------------
# DuckDuckGo search
# ---------------------------------------------------------------------------

def _ddgs_search(query):
    """
    Run a single DuckDuckGo search and return raw results.

    Uses the ddgs library. Returns a list of result dicts.
    """
    try:
        from ddgs import DDGS
    except ImportError:
        logger.warning(
            "ddgs library not installed; install with: pip install ddgs"
        )
        return []

    def _do_search():
        with DDGS() as ddgs:
            results = list(ddgs.text(
                query,
                max_results=10,
                timelimit="m",  # past month
            ))
        return results

    try:
        return _retry_with_backoff(_do_search, max_retries=3, base_delay=1.0)
    except Exception as exc:
        logger.error("DuckDuckGo search failed for query %r: %s", query, exc)
        return []


# ---------------------------------------------------------------------------
# Lead extraction from search results
# ---------------------------------------------------------------------------

def _extract_leads_from_results(results, source):
    """
    Convert a list of DuckDuckGo search results into lead dicts.

    Each result becomes at most one lead. URLs pointing to known article
    or social-media domains (not business websites) are skipped.
    """
    SKIP_DOMAINS = {
        "linkedin.com",
        "x.com",
        "twitter.com",
        "facebook.com",
        "youtube.com",
        "medium.com",
        "substack.com",
        "wikipedia.org",
        "quora.com",
        "reddit.com",
        "news.ycombinator.com",
        "glassdoor.com",
        "crunchbase.com",
        "g2.com",
        "clutch.co",
    }

    leads = []
    seen_domains = set()
    for r in results:
        lead = _parse_search_result(r, source)
        if not lead:
            continue
        if lead["domain"] in SKIP_DOMAINS:
            continue
        if lead["domain"] in seen_domains:
            continue
        seen_domains.add(lead["domain"])
        leads.append(lead)
    return leads


# ---------------------------------------------------------------------------
# Main discovery function
# ---------------------------------------------------------------------------

def discover_leads(
    db_path="leads.db",
    max_actions: int | None = None,
    max_queries: int | None = None,
):
    """
    Run discovery: generate queries, execute them via DuckDuckGo, parse
    results into leads, deduplicate by domain, check suppression list, and
    insert new leads into the database with status='new'.

    Args:
        db_path: Path to the SQLite database.
        max_actions: Cap on how many new leads to insert (default from config).
        max_queries: Cap on how many search queries to run (default from config).

    Returns:
        List of inserted lead dicts.
    """
    if max_actions is None:
        max_actions = MAX_ACTIONS_PER_RUN
    if max_queries is None:
        max_queries = _get_config_int("DISCOVERY_QUERIES_PER_RUN", 25)

    from db import transaction

    queries = generate_queries(max_queries=max_queries)
    logger.info("Generated %d discovery queries", len(queries))

    inserted = []
    action_count = 0

    for query in queries:
        if action_count >= max_actions:
            logger.info("Reached MAX_ACTIONS_PER_RUN (%d), stopping.", max_actions)
            break

        source = f"duckduckgo: {query[:60]}"
        results = _ddgs_search(query)
        if not results:
            logger.debug("No results for query: %s", query)
            continue

        leads = _extract_leads_from_results(results, source)
        logger.info("Query %r yielded %d leads", query[:40], len(leads))

        for lead in leads:
            if action_count >= max_actions:
                break

            domain = lead["domain"]

            # Check suppression list.
            with transaction(db_path) as conn:
                if is_suppressed(conn, domain):
                    logger.info("Skipping suppressed domain: %s", domain)
                    continue

                # Check if already in DB (dedupe).
                existing = get_lead_by_domain(conn, domain)
                if existing:
                    logger.debug("Lead already exists: %s", domain)
                    continue

                # Insert new lead.
                lead_id = upsert_lead(
                    conn,
                    domain=domain,
                    company=lead["company"],
                    website=lead["website"],
                    source=lead["source"],
                    status="new",
                )
                action_count += 1
                inserted.append({**lead, "id": lead_id})
                logger.info("Inserted lead #%d: %s (%s)", lead_id, lead["company"], domain)

    logger.info("Discovery complete: %d new leads inserted.", len(inserted))
    return inserted


def _get_config_int(name, default):
    """Read an integer env var, falling back to a default."""
    val = os.getenv(name)
    if val is None:
        return default
    try:
        return int(val)
    except ValueError:
        return default


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    leads = discover_leads()
    print(f"\nDiscovered {len(leads)} leads:")
    for l in leads:
        print(f"  - {l['company']} ({l['domain']})")